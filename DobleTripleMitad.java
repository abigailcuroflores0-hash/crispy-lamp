public class DobleTripleMitad {
    public static void main(String[] args) {

        int numero = 24;

        int doble = numero * 2;
        int triple = numero * 3;
        double mitad = numero / 2.0;

        System.out.println("Doble: " + doble);
        System.out.println("Triple: " + triple);
        System.out.println("Mitad: " + mitad);
    }
}