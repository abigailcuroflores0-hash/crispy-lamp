class ResiduoDivision {
    public static void main(String[] args) {
        int dividendo = 157;
        int divisor = 12;

        int cociente = dividendo / divisor;
        int residuo = dividendo % divisor;

        System.out.println("Cociente entero: " + cociente);
        System.out.println("Residuo: " + residuo);
    }
}